def payload_bits(*sentences):
    payload = "".join(s.split(",")[5] for s in sentences)
    fill = int(sentences[-1].split(",")[6].split("*")[0])
    out = []
    for c in payload:
        v = ord(c) - 48
        out += [int(b) for b in f"{v - 8 if v > 40 else v:06b}"]
    return np.array(out[:len(out) - fill], dtype=np.uint8)


# -- parsing, against published and independently generated messages -----------------


def test_published_class_a_position_reports():
    t, mmsi, f = parse(payload_bits("!AIVDM,1,1,,B,15M67FC000G?ufbE`FepT@3n00Sa,0*5C"))
    assert (t, mmsi, f["status"], f["sog"], f["cog"], f["heading"]) == (
        1, 366053209, "restricted manoeuvrability", 0.0, 219.3, 1)
    assert f["position"] == pytest.approx((37.802118, -122.341618), abs=1e-6)
    t, mmsi, f = parse(payload_bits("!AIVDM,1,1,,A,13u?etPv2;0n:dDPwUM1U1Cb069D,0*23"))
    assert (mmsi, f["sog"], f["cog"], f["heading"]) == (265547250, 13.9, 40.4, 41)
    assert f["position"] == pytest.approx((57.660353, 11.832977), abs=1e-6)


def test_class_b_position():
    t, mmsi, f = parse(payload_bits("!AIVDO,1,1,,A,B7Pab6@0@2UpM8JS;j07SwP00000,0*6D"))
